"""Текст угоди про обмін даними (УОД, DG-11, FR-24).

Формується з погодженого обсягу; фіксується версією й SHA-256.
"""

import hashlib

TEXT_VERSION = "1.0"

TEMPLATE = """УГОДА ПРО ОБМІН ДАНИМИ № {number} (GEDH, версія тексту {version})

Сторони: {requester_org} (Отримувач, в особі відповідальної особи: {responsible})
і {owner_org} (Постачальник).
Платформа GEDH діє як посередник і не використовує дані в інших цілях.

1. Предмет. Постачальник надає Отримувачу доступ до набору «{dataset}»:
   країна — {country}, категорія — {category}, період даних — {period_start} … {period_end}.
   Строк дії доступу — {term_days} днів від прийняття угоди.{narrowed}
2. Мета використання: {purpose}
   Місце використання: {usage_place}
3. Отримувач зобов'язується:
   а) використовувати дані лише із зазначеною метою;
   б) не передавати дані третім особам і не публікувати їх у вигляді, що дозволяє відновити значення;
   в) після завершення строку видалити отримані дані й підтвердити видалення на платформі (DG-12);
   г) зберігати позначку «СИНТЕТИЧНІ ДАНІ» в похідних матеріалах (демо-платформа, D-04).
4. Кожне звернення до даних і кожне вивантаження записується в журнал аудиту платформи.
   DG-офіцер платформи може призупинити доступ у разі порушення умов.
5. Угода набирає чинності з моменту її прийняття Отримувачем на платформі; пропозиція чинна 14 днів.
"""


def render(**fields) -> str:
    narrowed = "\n   Обсяг звужено постачальником порівняно із заявкою." if fields.pop("narrowed") else ""
    return TEMPLATE.format(version=TEXT_VERSION, narrowed=narrowed, **fields)


def text_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()
